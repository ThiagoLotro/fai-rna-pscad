// size -> tamanho da entrada
double softmax(double* input, int k) {
	int size = 2;
	double output[2];
    double max = input[0];
    double sum = 0.0;

    // Para estabilidade numérica, subtrai o máximo
    for (int i = 1; i < size; i++) {
        if (input[i] > max) {
            max = input[i];
        }
    }

    // Calcula exponenciais e soma
    for (int i = 0; i < size; i++) {
        output[i] = exp(input[i] - max);
        sum += output[i];
    }

    // Normaliza
    for (int i = 0; i < size; i++) {
        output[i] = output[i] / sum;
    }
	
	return output[k];
}

